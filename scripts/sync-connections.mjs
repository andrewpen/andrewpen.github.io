#!/usr/bin/env node
// Copy the design system's composition records to where the wireframe can
// read them, recording WHERE THEY CAME FROM (P05-A02).
//
// The wireframe is static HTML served from this repository, so it cannot read
// node_modules at runtime and one copy is unavoidable. A copy with no
// provenance is how a surface comes to describe something that changed months
// ago — the failure this chunk exists to prevent — so the copy carries the
// package version and an integrity hash, and the wireframe displays them.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = resolve(ROOT, 'node_modules/@a3kds/design-system/docs/compositions.json');
const pkg = resolve(ROOT, 'node_modules/@a3kds/design-system/package.json');
const out = resolve(ROOT, 'wireframe/connections.json');

if (!existsSync(src)) {
  // Reported, never silently skipped. The wireframe then shows its
  // unavailable state, which is the honest outcome of a missing record.
  console.error(`@a3kds/design-system does not ship compositions.json at ${src}.\n` +
    `The wireframe will show its unavailable state. Install a package version that includes it.`);
  process.exit(2);
}

const records = JSON.parse(readFileSync(src, 'utf8'));
const version = JSON.parse(readFileSync(pkg, 'utf8')).version;
const integrity = createHash('sha256').update(readFileSync(src)).digest('hex').slice(0, 16);

// THE VERSION DOES NOT IDENTIFY THE BYTES. 0.1.0-alpha.4 is live on the public
// registry, and a locally packed candidate carries the same version string with
// different contents — so a record saying only "0.1.0-alpha.4" would let a
// candidate build pass for the published release. The specifier does identify
// them: pack-for-consumer.mjs names every tarball by its content hash.
const specifier = JSON.parse(readFileSync(resolve(ROOT, 'package.json'), 'utf8'))
  .dependencies?.['@a3kds/design-system'] ?? '(not a declared dependency)';
const local = specifier.startsWith('file:');

const build = syncedAt => JSON.stringify({
  _note: 'GENERATED by scripts/sync-connections.mjs from the installed @a3kds/design-system. Never hand-edit: the wireframe displays the provenance below, and a hand-edit would make it lie.',
  source: { package: '@a3kds/design-system', version, integrity, specifier,
    installedFrom: local ? 'a local candidate tarball, NOT the public registry' : 'the public registry',
    versionCaveat: 'version is what the package declares. It does not identify these bytes: a local candidate shares the version string of the published release, so read specifier and integrity for identity.' },
  syncedAt,
  ...records,
}, null, 2) + '\n';

// syncedAt records when this record last CHANGED, not when the command last
// ran. A fresh timestamp on every run rewrote the file on every build, so the
// working tree was dirty after any build and "did the record actually change?"
// could not be answered from the diff — the one question a generated,
// committed artifact has to keep answerable.
const previous = existsSync(out) ? readFileSync(out, 'utf8') : null;
const now = new Date().toISOString().replace(/\.\d+Z$/, 'Z');
const carried = previous ? (JSON.parse(previous).syncedAt ?? now) : now;
const unchanged = previous !== null && build(carried) === previous;

mkdirSync(dirname(out), { recursive: true });
if (!unchanged) writeFileSync(out, build(now));
console.log(`wireframe/connections.json ${unchanged ? '== (unchanged)' : '<-'} @a3kds/design-system@${version} (${integrity})`);
